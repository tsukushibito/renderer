use std::path::PathBuf;

fn main() {
    let mut args = std::env::args_os().skip(1);
    let output = PathBuf::from(args.next().expect("usage: renderer-d3d12-bindings OUTPUT"));
    assert!(args.next().is_none(), "expected one output path");
    let filters = include_str!("../filters.txt")
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'));
    windows_bindgen::builder()
        // The exact windows-default package, its bundled metadata and checksum
        // are fixed by this standalone tool's checked-in Cargo.lock.
        .input_bytes(windows_default::WIN32)
        .flat()
        .filters(filters)
        .output(&output)
        .write();
    let generated = std::fs::read_to_string(&output).expect("read generated bindings");
    std::fs::write(
        output,
        format!(
            "// Generated by windows-bindgen 0.100.0 from windows-default 0.100.0.\n\
             // Regenerate using scripts/regenerate-d3d12-bindings.ps1.\n\
             // SPDX-License-Identifier: MIT OR Apache-2.0\n{generated}"
        ),
    )
    .expect("write generated binding provenance");
}
