// Updating the browser bundle is a preparation step; mdBook builds use the checked-in bundle.
import { build } from "esbuild";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const directory = path.dirname(fileURLToPath(import.meta.url));
const vendor = path.resolve(directory, "../../docs/theme/vendor");
const { version } = JSON.parse(await readFile(path.join(directory, "node_modules/mermaid/package.json"), "utf8"));
const result = await build({
    absWorkingDir: directory,
    stdin: { contents: 'import mermaid from "mermaid"; window.mermaid = mermaid;', resolveDir: directory },
    bundle: true,
    format: "iife",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "eof",
    write: false,
    banner: { js: `/* Mermaid ${version}; generated by tools/docs/bundle_mermaid.mjs. */` },
});
if (result.outputFiles.length !== 1) throw new Error("Expected a self-contained Mermaid JavaScript bundle");
const bundle = result.outputFiles[0].contents;
const hash = createHash("sha256").update(bundle).digest("hex");
const files = new Map([
    ["mermaid.min.js", bundle],
    ["mermaid-LICENSE.txt", await readFile(path.join(directory, "node_modules/mermaid/LICENSE"))],
    ["README.txt", Buffer.from(`Mermaid ${version} (MIT)\nSource: https://www.npmjs.com/package/mermaid/v/${version}\nBundled with pinned esbuild; third-party notices are retained in mermaid.min.js.\nSHA-256: ${hash}\nReproduce: npm ci --ignore-scripts --prefix tools/docs\n           npm run bundle --prefix tools/docs\nmdbook-mermaid 0.17.1 transforms Markdown; this bundle renders the diagrams.\n`)],
]);
for (const [name, data] of files) {
    const destination = path.join(vendor, name);
    if (process.argv.includes("--check")) {
        if (!Buffer.from(data).equals(await readFile(destination))) {
            throw new Error(`Outdated Mermaid asset: ${name}; run npm run bundle --prefix tools/docs`);
        }
    } else await writeFile(destination, data);
}
console.log(`Mermaid ${version}, SHA-256 ${hash}${process.argv.includes("--check") ? " verified" : " bundled"}`);
